'use strict';

// Regression tests for the grocery-list date-range/plan-date alignment bug:
// grocery-list.html's weekStart was hardcoded in init() to
// getMondayOfWeek(new Date()) — the calendar week containing the real-world
// "today" — with zero navigation to any other week. A plan generated for a
// date outside that single week (e.g. Monday Aug 31 when "today" falls in
// the Aug 24-30 week) was therefore permanently unreachable from the grocery
// list, even though:
//   - the server has no date-window restriction at all (grocery-list/:planId
//     routes are scoped only by planId + day name + session ownership), and
//   - the planId for that week was already saved under its own correct
//     weekStart key by savePlanId() at generation time.
//
// The fix extracts the week-loading logic into loadWeek(weekStart) and adds
// changeWeek(deltaWeeks), which shifts weekStart by +/-7 local-calendar days
// and reloads — mirroring the planner's own unbounded day-by-day navigation
// (planner-controller.js's changeDate). This does not change how a day's
// list is fetched/rendered (still selectDay() against the existing
// planId+day), so no new list is ever generated by navigating.
//
// Runs the REAL public/js/groceries-sync.js source in a sandboxed VM, same
// pattern as tests/grocery-list-planid-flow.test.js and
// tests/planner-local-date.test.js.

const { test, describe, after } = require('node:test');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');

const RAW_SOURCE = fs.readFileSync(path.join(__dirname, '..', 'public', 'js', 'groceries-sync.js'), 'utf8');
const SOURCE = RAW_SOURCE + `
globalThis.__t = {
  get planId() { return planId; }, set planId(v) { planId = v; },
  get weekStart() { return weekStart; }, set weekStart(v) { weekStart = v; },
  get weekDates() { return weekDates; },
  get selectedDay() { return selectedDay; },
  get availableDays() { return availableDays; },
  get groceryList() { return groceryList; },
  loadWeek, changeWeek, selectDay, savePlanId, loadPlanId, toLocalDateStr, getMondayOfWeek,
};
`;

const ORIGINAL_TZ = process.env.TZ;
after(() => {
  if (ORIGINAL_TZ === undefined) delete process.env.TZ;
  else process.env.TZ = ORIGINAL_TZ;
});
function withTz(tz, fn) {
  const prev = process.env.TZ;
  process.env.TZ = tz;
  try { return fn(); } finally {
    if (prev === undefined) delete process.env.TZ; else process.env.TZ = prev;
  }
}

function makeLocalStorage(initial = {}) {
  const store = new Map(Object.entries(initial));
  return {
    getItem: (k) => (store.has(k) ? store.get(k) : null),
    setItem: (k, v) => store.set(k, String(v)),
    removeItem: (k) => store.delete(k),
    clear: () => store.clear(),
  };
}

function makeSandbox(fetchImpl, localStorageInitial) {
  const calls = [];
  const stubFn = (name) => (...args) => { calls.push({ name, args }); };
  const sandbox = {
    localStorage: makeLocalStorage(localStorageInitial),
    fetch: (...args) => { calls.push({ name: 'fetch', args }); return fetchImpl(...args); },
    document: { getElementById: () => ({ textContent: '', style: {}, classList: { add() {}, remove() {} } }) },
    console,
    setTimeout: (fn) => { fn(); },
    renderGroceryList: stubFn('renderGroceryList'),
    renderEmpty: stubFn('renderEmpty'),
    renderDaySwitcher: stubFn('renderDaySwitcher'),
    updateProgress: stubFn('updateProgress'),
    showToast: stubFn('showToast'),
  };
  sandbox.window = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(SOURCE, sandbox, { filename: 'groceries-sync.js' });
  return { sandbox, calls };
}

describe('A/K — changeWeek(1) crosses the Sunday->Monday and month boundary that trapped Aug 31', () => {
  test('from the week of Aug 24-30, changeWeek(1) reaches the week containing Monday Aug 31 (Sep 1 falls in the same week)', async () => {
    const { sandbox } = makeSandbox(async (url) => {
      if (String(url).endsWith('/days')) return { ok: true, json: async () => ({ success: true, days: ['Monday'] }) };
      return { ok: true, json: async () => ({ success: true, groceryList: { categories: {} } }) };
    });
    await sandbox.__t.loadWeek('2026-08-24'); // Monday of the week containing "today" in the bug report
    const beforeDates = [...sandbox.__t.weekDates].map(d => d.date);
    assert.equal(JSON.stringify(beforeDates), JSON.stringify(['2026-08-24','2026-08-25','2026-08-26','2026-08-27','2026-08-28','2026-08-29','2026-08-30']));

    await sandbox.__t.changeWeek(1);

    assert.equal(sandbox.__t.weekStart, '2026-08-31');
    const dates = [...sandbox.__t.weekDates].map(d => d.date);
    assert.equal(JSON.stringify(dates), JSON.stringify(['2026-08-31','2026-09-01','2026-09-02','2026-09-03','2026-09-04','2026-09-05','2026-09-06']));
    assert.equal(dates[0], '2026-08-31', 'Monday Aug 31 is now navigable');
    assert.equal(dates[1], '2026-09-01', 'month boundary Aug 31 -> Sep 1 crossed correctly within the same week');
  });
});

describe('B/C — the correct existing list loads for the newly-reached week, never the prior week\'s', () => {
  test('selectDay after changeWeek fetches the NEW weekStart\'s planId/day, not the old one\'s', async () => {
    const planIds = { '2026-08-24': 'plan-this-week', '2026-08-31': 'plan-next-week' };
    const fetchedUrls = [];
    const { sandbox } = makeSandbox(async (url) => {
      fetchedUrls.push(String(url));
      if (String(url).includes('/plan-this-week/')) {
        if (String(url).endsWith('/days')) return { ok: true, json: async () => ({ success: true, days: ['Sunday'] }) };
        return { ok: true, json: async () => ({ success: true, groceryList: { categories: { produce: [{ name: 'Sunday kale' }] } } }) };
      }
      if (String(url).includes('/plan-next-week/')) {
        if (String(url).endsWith('/days')) return { ok: true, json: async () => ({ success: true, days: ['Monday'] }) };
        return { ok: true, json: async () => ({ success: true, groceryList: { categories: { produce: [{ name: 'Monday spinach' }] } } }) };
      }
      return { ok: true, json: async () => ({ success: true, days: [] }) };
    }, { mealzy_grocery_plan_ids: JSON.stringify(planIds) });

    await sandbox.__t.loadWeek('2026-08-24');
    assert.equal(sandbox.__t.planId, 'plan-this-week');

    await sandbox.__t.changeWeek(1);

    assert.equal(sandbox.__t.planId, 'plan-next-week', 'the planId keyed to the NEW weekStart is loaded, not reused from the old week');
    assert.ok(fetchedUrls.some(u => u.includes('plan-next-week')), 'the new week\'s plan was actually fetched');
  });
});

