describe('N — navigating into a week with NO saved planId shows a truthful empty state, never stale/borrowed data', () => {
  test('changeWeek into a plan-less week: no generation call, no stale list, no crash, clean empty state, and navigating back restores the original list intact', async () => {
    // Dates deliberately far from any plausible real system clock, so
    // selectedDay always defaults to weekDates[0] ("Monday") regardless of
    // what "today" the test happens to run on — see loadWeek()'s
    // todayEntry-vs-weekDates[0] fallback. Only "2030-01-07" has a planId;
    // "2030-01-14" (one week later) has none — e.g. the user never
    // generated a plan for that week.
    const planIds = { '2030-01-07': 'plan-this-week' };
    const fetchedUrls = [];
    // Matches the day-content URL for ANY day name, not just "Monday", so
    // this stays robust even if some future host clock did land inside
    // this window.
    const { sandbox, calls } = makeSandbox(async (url) => {
      fetchedUrls.push(String(url));
      if (String(url).includes('/plan-this-week/days')) return { ok: true, json: async () => ({ success: true, days: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'] }) };
      if (/\/plan-this-week\/[A-Za-z]+$/.test(String(url))) {
        return { ok: true, json: async () => ({ success: true, groceryList: { categories: { produce: [{ id: 'item-1', name: 'Kale', checked: true, actualCost: 3.75 }] } } }) };
      }
      throw new Error(`unexpected fetch during the plan-less week: ${url}`);
    }, { mealzy_grocery_plan_ids: JSON.stringify(planIds) });

    // Load the week that HAS a plan first, so there is a real list on screen
    // (with checked state + actualCost) before navigating away from it.
    await sandbox.__t.loadWeek('2030-01-07');
    assert.equal(sandbox.__t.groceryList.categories.produce[0].name, 'Kale');
    assert.equal(sandbox.__t.groceryList.categories.produce[0].checked, true);
    assert.equal(sandbox.__t.groceryList.categories.produce[0].actualCost, 3.75);
    const selectedDayInFirstWeek = sandbox.__t.selectedDay;
    const fetchCountBeforeNav = calls.filter(c => c.name === 'fetch').length;

    // Navigate one week forward, into the week with no planId at all — must
    // not throw, and (per the mock's throw-on-unexpected-fetch above) must
    // make zero fetch calls, since refreshAvailableDays() and selectDay()
    // both short-circuit on a missing planId before ever calling fetch.
    await assert.doesNotReject(() => sandbox.__t.changeWeek(1));

    assert.equal(sandbox.__t.weekStart, '2030-01-14');
    assert.equal(sandbox.__t.planId, null, 'no planId exists for this week');
    assert.equal(sandbox.__t.availableDays.size, 0, 'no available days fabricated for this week');
    assert.equal(sandbox.__t.groceryList, null, '1 & 4: no list — not a fresh generation, and not the prior week\'s list leaking through');
    assert.equal(sandbox.__t.selectedDay, 'Monday', 'week starting Jan 14 2030 defaults to its own Monday, unrelated to the prior week\'s selected day');

    const fetchCountAfterNav = calls.filter(c => c.name === 'fetch').length;
    assert.equal(fetchCountAfterNav, fetchCountBeforeNav, '2: zero fetch calls were made while on the plan-less week (nothing to generate, nothing to leak)');
    const genCalls = calls.filter(c => c.name === 'fetch' && String(c.args[0]).includes('/api/generate-grocery-list'));
    assert.equal(genCalls.length, 0, '1/2: /api/generate-grocery-list was never called');

    const emptyCalls = calls.filter(c => c.name === 'renderEmpty');
    assert.equal(emptyCalls.length, 1, '6: the truthful empty state was rendered exactly once for the plan-less week');
    const groceryRenderCallsSoFar = calls.filter(c => c.name === 'renderGroceryList').length;
    assert.equal(groceryRenderCallsSoFar, 1, 'renderGroceryList must not have fired again while on the plan-less week (still just the original week\'s one render)');

    // 3/4 (DOM-level): renderEmpty() in the real groceries-ui.js fully replaces
    // #groceryContainer's innerHTML (see renderEmpty()), so once it has run,
    // no prior week's or other week's items can remain in the DOM — verified
    // here by confirming renderEmpty ran and renderGroceryList did not run
    // again in between, i.e. nothing re-painted stale content afterward.

    // 7/8/9: navigate back — Previous still works, and it must restore the
    // ORIGINAL list, unmodified. refreshAvailableDays() always re-checks
    // /days for a week with a real planId (by design, independent of this
    // fix), but the day's CONTENT must come back from the local cache
    // (setCachedDayList, written on the original fetch) rather than a
    // second content fetch.
    const contentUrlPattern = new RegExp(`/plan-this-week/${selectedDayInFirstWeek}$`);
    const contentUrlsBefore = fetchedUrls.filter(u => contentUrlPattern.test(u)).length;
    await assert.doesNotReject(() => sandbox.__t.changeWeek(-1));
    assert.equal(sandbox.__t.weekStart, '2030-01-07');
    assert.equal(sandbox.__t.selectedDay, selectedDayInFirstWeek, 'returns to the same day that was selected before navigating away');
    assert.ok(sandbox.__t.groceryList, '8: the original week\'s list is restored');
    const restored = sandbox.__t.groceryList.categories.produce[0];
    assert.equal(restored.name, 'Kale');
    assert.equal(restored.checked, true, '9: checked state survived the round trip');
    assert.equal(restored.actualCost, 3.75, '9: actualCost survived the round trip');

    const contentUrlsAfter = fetchedUrls.filter(u => contentUrlPattern.test(u)).length;
    assert.equal(contentUrlsAfter, contentUrlsBefore, '8: the day\'s content came from the local cache, not a second content fetch');
  });
});
