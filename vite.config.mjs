import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Marketing-page React build (Phase 1: homepage; Phase 2A: pricing, upgrade,
// login, reset-password). Source lives in client/, output goes to dist/ at the
// repo root; express.static(dist) is mounted before public/, so any page built
// here wins over its legacy public/*.html counterpart automatically.
export default defineConfig({
  root: 'client',
  plugins: [react()],
  publicDir: false,
  resolve: {
    alias: { '@': path.resolve(__dirname, 'client/src') }
  },
  build: {
    outDir: '../dist',
    emptyOutDir: true,
    rollupOptions: {
      input: {
        index: path.resolve(__dirname, 'client/index.html'),
        pricing: path.resolve(__dirname, 'client/pricing.html'),
        upgrade: path.resolve(__dirname, 'client/upgrade.html'),
        login: path.resolve(__dirname, 'client/login.html'),
        'reset-password': path.resolve(__dirname, 'client/reset-password.html')
      }
    }
  },
  server: {
    proxy: {
      '/api': 'http://localhost:3000',
      '/js': 'http://localhost:3000',
      '/css': 'http://localhost:3000',
      '/fonts': 'http://localhost:3000',
      '/manifest.json': 'http://localhost:3000',
      '/favicon.svg': 'http://localhost:3000',
      '/sw.js': 'http://localhost:3000',
      // Stripe payment-link URLs are generated by server.js from env vars.
      // MUST stay a blocking (non-defer) script on pages with a billing toggle.
      '/stripe-config.js': 'http://localhost:3000',
      // Google OAuth entry + callback live on the Express server.
      '/auth': 'http://localhost:3000'
    }
  }
});
