window.t = function(key) {
  const lang = (() => { try { return JSON.parse(localStorage.getItem('mealzy_profile') || '{}').language || 'en'; } catch(e) { return 'en'; } })();
  const dict = window.MEALZY_TRANSLATIONS[lang] || window.MEALZY_TRANSLATIONS.en;
  return dict[key] || window.MEALZY_TRANSLATIONS.en[key] || key;
};

window.applyTranslations = function() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = window.t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
};

window.applyNavTranslations = function() {
  const navMap = {
    'dashboard.html':    window.t('nav_dashboard'),
    'meal-planner.html': window.t('nav_planner'),
    'grocery-list.html': window.t('nav_groceries'),
    'analytics.html':    window.t('nav_analytics'),
    'ai-coach.html':     window.t('nav_coach'),
    'settings.html':     window.t('nav_settings')
  };
  document.querySelectorAll('.sidebar-nav a').forEach(a => {
    const href = a.getAttribute('href');
    if (navMap[href]) {
      const icon = a.querySelector('.nav-icon');
      a.textContent = '';
      if (icon) a.appendChild(icon);
      a.appendChild(document.createTextNode(' ' + navMap[href]));
    }
  });
  document.querySelectorAll('[onclick="signOut()"]').forEach(btn => {
    const icon = btn.querySelector('svg');
    btn.textContent = '';
    if (icon) btn.appendChild(icon);
    btn.appendChild(document.createTextNode(' ' + window.t('sign_out')));
  });
  // Fix generate button label (target span, not whole button — preserves SVG icon)
  const genLabel = document.getElementById('generateBtnLabel');
  if (genLabel) genLabel.textContent = window.t('btn_generate');
  // Coach input placeholder
  const coachInput = document.getElementById('messageInput');
  if (coachInput) coachInput.placeholder = window.t('coach_placeholder');
  // Apply all data-i18n attributes
  window.applyTranslations();
};
